"""
    SymbolGroup(op)

A group on the elements `0:m-1` with identity 0, by its table: `op[a + 1,
b + 1]` is the product `a b`, and `inv[a + 1]` the inverse of `a`. A starter
over a cyclic group needs no table; its arithmetic is modulo m.
"""
struct SymbolGroup
    op::Matrix{Int}
    inv::Vector{Int}
end

SymbolGroup(op::Matrix{Int}) = SymbolGroup(op, [findfirst(==(0), view(op, a, :)) - 1 for a in axes(op, 1)])

"Z_m as a table, which agrees with arithmetic modulo m (a test checks)."
_cyclic_group(m::Int) = SymbolGroup([mod(a + b, m) for a in 0:(m - 1), b in 0:(m - 1)])

"Z_3 × Z_3. The element (a, b), printed `ab`, is 3a + b."
_z3z3() = SymbolGroup([3 * mod(a ÷ 3 + b ÷ 3, 3) + mod(a % 3 + b % 3, 3) for a in 0:8, b in 0:8])

"The group of order 6 with x^3 = y^2 = 1 and y x y = x^2. The element x^i y^j is i + 3j."
_s3() = SymbolGroup([mod(a % 3 + (iseven(a ÷ 3) ? 1 : -1) * (b % 3), 3) + 3 * mod(a ÷ 3 + b ÷ 3, 2)
                     for a in 0:5, b in 0:5])

"The table of a starter's `group`, or `nothing` for the cyclic group, whose arithmetic is modulo m."
_symbol_group(group::Symbol) = group === :S3 ? _s3() : group === :Z3xZ3 ? _z3z3() : nothing

"""
    _parse_starter(text, group = :Zm) -> Vector{Int}

A starter as the papers print it: `∞i` for the fixed symbol inf_i, written
`-(i + 1)`; `*` for a free entry, `_FREE`; and the group's elements as
integers (`:Zm`), as two digits `ab` of Z_3 × Z_3 (`:Z3xZ3`), or as words in
x and y (`:S3`), each written as its element number (`_symbol_group`).
"""
function _parse_starter(text::AbstractString, group::Symbol = :Zm)
    return map(split(text)) do token
        startswith(token, "∞") && return -(parse(Int, token[nextind(token, 1):end]) + 1)
        token == "*" && return _FREE
        if group === :S3
            word = findfirst(==(token), ("1", "x", "x2", "y", "xy", "x2y"))
            word === nothing && throw(ArgumentError("$(repr(token)) is not an element of S3"))
            return word - 1
        end
        group === :Z3xZ3 && return 3 * parse(Int, token[1:1]) + parse(Int, token[2:2])
        return parse(Int, token)
    end
end

"A Meagher & Stevens 2005 vector over Z_v, in which 0 is the fixed symbol and `1:v-1` turn, as a parsed starter."
_from_meagher_stevens(text::AbstractString) = [x == 0 ? _INF : x - 1 for x in parse.(Int, split(text))]
