# Cover starters as data (plan §5.4, "Cover starters are data"): the vectors
# the papers print, and the ones found by exhaustive search, each read by
# `_parse_starter`. `_fixed_starter_array` and `_distinct_starter_array` in
# construction_arrays.jl develop one into a covering array of strength 2; the
# catalog (construction_catalog.jl) offers each as a candidate; and
# test/test_catalog.jl builds an array from every one and checks it by brute
# force. Sources, in papers/:
#
#   Colbourn 2004            2004_Colbourn_Combinatorial_Aspects_of_Covering_Arrays.pdf (journal pages)
#   Meagher & Stevens 2005   2004_Meagher_Group_Construction_of_Covering_Arrays.pdf
#   Lobb et al. 2012         2012_Lobb_Cover_Starters_for_Covering_Arrays_of_Strength_Two.pdf
#
# A starter is printed as a vector of length k: `∞i` is the fixed symbol
# inf_i, `*` an entry that may hold anything, and the rest are elements of a
# group of order v - f, which the papers print as integers modulo v - f, as
# two digits `ab` of Z_3 × Z_3, or as words in x and y. Development turns the
# k columns cyclically and moves the group's elements by the group, leaving
# the f fixed symbols alone (`_developed`). Every vector here is correct as
# printed, except one, marked where it is.

